export function defaultHelpTab(role?: string | null): HelpTabId {
  if (role === "manager") return "input";
  if (role === "analytic" || role === "regional_director") return "reports";
  if (role === "admin") return "admin";
  return "start";
}

export function helpTabById(id: HelpTabId): HelpTab {
  return HELP_TABS.find((tab) => tab.id === id) || HELP_TABS[0];
}

export type HelpSearchHit = {
  tabId: HelpTabId;
  tabLabel: string;
  block: HelpBlock;
};

export function searchHelp(query: string): HelpSearchHit[] {
  const needle = query.trim().toLowerCase();
  if (needle.length < 2) return [];
  const hits: HelpSearchHit[] = [];
  for (const tab of HELP_TABS) {
    for (const block of tab.blocks) {
      const blob = [block.title, block.lead, ...(block.steps || []), ...(block.notes || [])]
        .filter(Boolean)
        .join(" ")
        .toLowerCase();
      if (blob.includes(needle)) hits.push({ tabId: tab.id, tabLabel: tab.label, block });
    }
  }
  return hits;
}
