export function defaultHelpTab(role?: string | null): HelpTabId {
  if (role === "manager") return "input";
  if (role === "analytic" || role === "regional_director") return "reports";
  if (role === "admin") return "admin";
  return "start";
}

export function helpTabById(id: HelpTabId): HelpTab {
  return HELP_TABS.find((tab) => tab.id === id) || HELP_TABS[0];
}
